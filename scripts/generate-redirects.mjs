// Writes site/public/_redirects (Cloudflare Pages format) from the files in docs/.
//
// The documentation used to be served from the site root with trailing slashes
// (/getting-started/, /reference/cli/). It now lives under /docs, so every page gets a
// permanent redirect from its old address, with and without the trailing slash.
// Pages that were removed keep both of their addresses and point at the page that
// replaced them.
//
// Usage:
//   node scripts/generate-redirects.mjs           rewrite the file
//   node scripts/generate-redirects.mjs --check   fail if the file is out of date
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const docs = path.join(root, "docs");
const output = path.join(root, "site", "public", "_redirects");

// Addresses the new site serves itself. A redirect from one of these would hide it.
const reserved = new Set(["", "docs", "schema", "_nuxt"]);

// Removed pages and where their readers should land now.
const retired = new Map([
  ["how-to/swarm-cluster", "/docs/how-to/cluster"],
]);

const pages = (await markdownFiles(docs))
  .map((file) =>
    path.relative(docs, file).split(path.sep).join("/").replace(/\.md$/, ""),
  )
  .map((page) => page.replace(/(^|\/)index$/, ""))
  .sort();

const lines = [
  "# Generated by scripts/generate-redirects.mjs from the files in docs/. Do not edit.",
  "# Old documentation addresses (served from the site root) to their place under /docs.",
];
const skipped = [];
for (const page of pages) {
  if (reserved.has(page.split("/")[0])) {
    if (page) skipped.push(page);
    continue;
  }
  lines.push(`/${page} /docs/${page} 301`, `/${page}/ /docs/${page} 301`);
}
for (const [page, destination] of [...retired].sort()) {
  for (const address of [`/${page}`, `/docs/${page}`]) {
    lines.push(`${address} ${destination} 301`, `${address}/ ${destination} 301`);
  }
}
const content = `${lines.join("\n")}\n`;

if (skipped.length > 0) {
  console.warn(
    `No redirect written for pages under a reserved address: ${skipped.join(", ")}`,
  );
}

if (process.argv.includes("--check")) {
  const current = await readFile(output, "utf8").catch(() => "");
  if (current !== content) {
    console.error(
      "site/public/_redirects is out of date. Run: node scripts/generate-redirects.mjs",
    );
    process.exitCode = 1;
  } else {
    console.log("site/public/_redirects is up to date.");
  }
} else {
  await writeFile(output, content);
  console.log(
    `Wrote ${(lines.length - 2) / 2} redirects (two lines each) to site/public/_redirects.`,
  );
}

async function markdownFiles(directory) {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const entryPath = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await markdownFiles(entryPath)));
    else if (entry.isFile() && entry.name.endsWith(".md"))
      files.push(entryPath);
  }
  return files;
}
