#!/usr/bin/env node
// Generates the mm brand assets in brand/ and the site icons derived from them.
//
//   node scripts/generate-brand.mjs                 SVG files only
//   node scripts/generate-brand.mjs --png           also render PNG and ICO files (needs Playwright's
//                                                   Chromium, which core/ui already installs)
//   node scripts/generate-brand.mjs --social-card   also render only site/public/og.png
//
// Without core/ui's dependencies, point MM_PLAYWRIGHT at a `playwright` or `playwright-core`
// package directory and MM_CHROMIUM at a Chromium binary.
//
// The letterforms are Geist Mono Bold "m" (SIL Open Font License), outlined so the files
// carry no font dependency. Edit the geometry here, not the generated files.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const brand = path.join(root, "brand");
const sitePublic = path.join(root, "site/public");

const LIME = "#c6f24e";
const INK = "#0d1203";
const WHITE = "#f1f3f2";

// One "m" on a 1000-unit em: x 28..572, y -548..0 (baseline at 0), advance 600.
const M =
  "M155 0L28 0L28-536L139-536L142-456Q153-493 173-515Q201-548 244-548Q294-548 317-515Q332-491 341-450Q353-490 376-514Q409-548 457-548Q516-548 544-505.5Q572-463 572-372L572 0L445 0L445-345Q445-397 435.5-415Q426-433 406-433Q392-433 381.5-424Q371-415 365-395.5Q359-376 359-344L359 0L241 0L241-345Q241-395 232-414Q223-433 202-433Q188-433 177-424Q166-415 160.5-395.5Q155-376 155-344L155 0Z";
const PAIR_GAP = 560; // advance 600 with -0.04em tracking
const INK_BOX = { x: 28, width: 572 + PAIR_GAP - 28, height: 548 };

/** The two letters as path data, scaled and placed with their ink box at (x, y). */
function letters(x, y, scale) {
  const place = (dx) =>
    M.replace(/([MLQ])([^MLQZ]*)/g, (_, command, numbers) => {
      const values = numbers.trim().split(/[\s,]+|(?<=\d)(?=-)/).map(Number);
      const out = values.map((value, index) =>
        index % 2 === 0
          ? round(x + (value + dx - INK_BOX.x) * scale)
          : round(y + (value + INK_BOX.height) * scale),
      );
      return command + out.join(" ");
    });
  return `${place(0)}${place(PAIR_GAP)}`;
}

function round(value) {
  return Number(value.toFixed(2));
}

function roundedRect(width, height, radius) {
  return `M${radius} 0H${width - radius}A${radius} ${radius} 0 0 1 ${width} ${radius}V${height - radius}A${radius} ${radius} 0 0 1 ${width - radius} ${height}H${radius}A${radius} ${radius} 0 0 1 0 ${height - radius}V${radius}A${radius} ${radius} 0 0 1 ${radius} 0Z`;
}

function svg(width, height, title, body) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" role="img" aria-label="${title}"><title>${title}</title>${body}</svg>\n`;
}

/** The block from the terminal header: a wide tile with the letters centred. */
function mark({ tile, glyph, knockout = false }) {
  const width = 208;
  const height = 155;
  const scale = 0.1;
  const x = (width - INK_BOX.width * scale) / 2;
  const y = (height - INK_BOX.height * scale) / 2;
  const block = roundedRect(width, height, 28);
  const type = letters(x, y, scale);
  return svg(
    width,
    height,
    "mm",
    knockout
      ? `<path fill="${tile}" fill-rule="evenodd" d="${block}${type}"/>`
      : `<path fill="${tile}" d="${block}"/><path fill="${glyph}" d="${type}"/>`,
  );
}

/** A square tile for favicons, avatars, and app icons. */
function icon({ tile, glyph }) {
  const size = 512;
  const scale = 0.31;
  const x = (size - INK_BOX.width * scale) / 2;
  const y = (size - INK_BOX.height * scale) / 2;
  return svg(
    size,
    size,
    "mm",
    `<path fill="${tile}" d="${roundedRect(size, size, 116)}"/><path fill="${glyph}" d="${letters(x, y, scale)}"/>`,
  );
}

const files = {
  "mm-mark.svg": mark({ tile: LIME, glyph: INK }),
  "mm-mark-inverse.svg": mark({ tile: INK, glyph: LIME }),
  "mm-mark-mono-black.svg": mark({ tile: "#000", knockout: true }),
  "mm-mark-mono-white.svg": mark({ tile: "#fff", knockout: true }),
  "mm-icon.svg": icon({ tile: LIME, glyph: INK }),
  "mm-icon-inverse.svg": icon({ tile: INK, glyph: LIME }),
};

await mkdir(brand, { recursive: true });
for (const [name, content] of Object.entries(files)) {
  await writeFile(path.join(brand, name), content);
}
await writeFile(path.join(sitePublic, "favicon.svg"), files["mm-icon.svg"]);
await writeFile(path.join(root, "core/ui/src/assets/favicon.svg"), files["mm-icon.svg"]);

// The UI kit draws the same mark inline, so the wordmark needs no font and never drifts.
const kitScale = 0.1;
await writeFile(
  path.join(root, "packages/ui/src/brand.ts"),
  `// Generated by scripts/generate-brand.mjs. Do not edit.
export const MARK_WIDTH = 208;
export const MARK_HEIGHT = 155;
export const MARK_RADIUS = 28;
export const MARK_LETTERS =
  "${letters((208 - INK_BOX.width * kitScale) / 2, (155 - INK_BOX.height * kitScale) / 2, kitScale)}";
`,
);
console.log(`Wrote ${Object.keys(files).length} SVG files to brand/, the site and dashboard favicons, and the kit mark`);

if (process.argv.includes("--png")) {
  await renderRasters();
} else if (process.argv.includes("--social-card")) {
  const browser = await launchBrowser();
  const page = await browser.newPage({ deviceScaleFactor: 1 });
  await writeFile(path.join(sitePublic, "og.png"), await socialCard(page));
  await browser.close();
  console.log("Wrote the social card to site/public/og.png");
}

async function launchBrowser() {
  const require = createRequire(path.join(root, "core/ui/package.json"));
  const { chromium } = require(process.env.MM_PLAYWRIGHT ?? "@playwright/test");
  return chromium.launch(process.env.MM_CHROMIUM ? { executablePath: process.env.MM_CHROMIUM } : {});
}

async function renderRasters() {
  const browser = await launchBrowser();
  const page = await browser.newPage({ deviceScaleFactor: 1 });

  async function png(source, width, height, background) {
    await page.setViewportSize({ width, height });
    await page.setContent(
      `<style>html,body{margin:0;background:${background ?? "transparent"}}svg{display:block;width:${width}px;height:${height}px}</style>${source}`,
    );
    return page.screenshot({ omitBackground: !background, clip: { x: 0, y: 0, width, height } });
  }

  const png_dir = path.join(brand, "png");
  await mkdir(png_dir, { recursive: true });
  let count = 0;
  for (const [name, variant] of [
    ["mm-mark", "mm-mark.svg"],
    ["mm-mark-inverse", "mm-mark-inverse.svg"],
    ["mm-mark-mono-black", "mm-mark-mono-black.svg"],
    ["mm-mark-mono-white", "mm-mark-mono-white.svg"],
  ]) {
    for (const width of [256, 512, 1024, 2048]) {
      const height = Math.round((width * 155) / 208);
      await writeFile(path.join(png_dir, `${name}-${width}.png`), await png(files[variant], width, height));
      count += 1;
    }
  }
  const icons = {};
  for (const size of [16, 32, 48, 64, 128, 180, 192, 256, 512, 1024]) {
    icons[size] = await png(files["mm-icon.svg"], size, size);
    await writeFile(path.join(png_dir, `mm-icon-${size}.png`), icons[size]);
    count += 1;
  }
  for (const size of [256, 512, 1024]) {
    await writeFile(
      path.join(png_dir, `mm-icon-inverse-${size}.png`),
      await png(files["mm-icon-inverse.svg"], size, size),
    );
    count += 1;
  }

  // Site icons: a multi-size favicon.ico and the touch icons browsers ask for by name.
  await writeFile(path.join(sitePublic, "favicon.ico"), ico([icons[16], icons[32], icons[48]], [16, 32, 48]));
  await writeFile(path.join(sitePublic, "apple-touch-icon.png"), icons[180]);
  await writeFile(path.join(sitePublic, "icon-192.png"), icons[192]);
  await writeFile(path.join(sitePublic, "icon-512.png"), icons[512]);
  await writeFile(path.join(sitePublic, "og.png"), await socialCard(page));
  await browser.close();
  console.log(`Wrote ${count} PNG files to brand/png/, and the site icons and social card to site/public/`);
}

/** The 1200x630 card shown when the site is shared. Uses the site's installed display font. */
async function socialCard(page) {
  const font = await readFile(
    path.join(root, "site/node_modules/@fontsource/barlow/files/barlow-latin-600-normal.woff2"),
  );
  await page.setViewportSize({ width: 1200, height: 630 });
  await page.setContent(`<style>
    @font-face { font-family: Barlow; font-weight: 600; src: url(data:font/woff2;base64,${font.toString("base64")}) format("woff2"); }
    html, body { margin: 0; }
    body {
      box-sizing: border-box; width: 1200px; height: 630px; padding: 76px 84px;
      display: flex; flex-direction: column; justify-content: space-between;
      color: ${WHITE}; font-family: Barlow, sans-serif;
      background:
        radial-gradient(ellipse 70% 80% at 85% 110%, rgb(198 242 78 / 26%), transparent 70%),
        radial-gradient(rgb(232 246 214 / 14%) 1.2px, transparent 1.6px) 0 0 / 30px 30px,
        #070908;
    }
    svg { display: block; width: 150px; height: auto; }
    h1 { margin: 0; font-size: 88px; font-weight: 600; line-height: 0.98; letter-spacing: -0.012em; }
    h1 span { color: ${LIME}; }
    h2 { margin: 26px 0 0; font-size: 36px; font-weight: 600; line-height: 1.2; color: #a9b3ad; }
    p { margin: 0; font: 500 27px ui-monospace, "DejaVu Sans Mono", monospace; color: #7f8883; }
    p b { color: ${LIME}; font-weight: 500; }
  </style>
  ${files["mm-mark.svg"]}
  <div>
    <h1>Turn a list of servers<br>into <span>one cluster.</span></h1>
    <h2>A Docker Swarm replacement for your Compose project.</h2>
  </div>
  <p><b>$</b> curl -LsSf https://modmon.dev/install.sh | sh</p>`);
  await page.evaluate(() => document.fonts.ready);
  return page.screenshot({ clip: { x: 0, y: 0, width: 1200, height: 630 } });
}

/** An ICO container holding PNG images. */
function ico(images, sizes) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(images.length, 4);
  let offset = 6 + 16 * images.length;
  const entries = images.map((image, index) => {
    const entry = Buffer.alloc(16);
    entry.writeUInt8(sizes[index], 0);
    entry.writeUInt8(sizes[index], 1);
    entry.writeUInt16LE(1, 4);
    entry.writeUInt16LE(32, 6);
    entry.writeUInt32LE(image.length, 8);
    entry.writeUInt32LE(offset, 12);
    offset += image.length;
    return entry;
  });
  return Buffer.concat([header, ...entries, ...images]);
}
